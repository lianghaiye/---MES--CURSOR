function formatReportDate(d = new Date()) {
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

function daysAgo(n) {
  return dayjs().subtract(n, 'day').format('YYYY-MM-DD')
}

function dateTime(day, time) {
  return `${day} ${time}`
}

function taskNo(day, seq) {
  return `T${day.replace(/-/g, '')}${String(seq).padStart(3, '0')}`
}

function createTask(partial) {
  const goodQty = Number(partial.goodQty) || 0
  const defectQty = Number(partial.defectQty) || 0
  return {
    source: 'workorder',
    finishedQty: goodQty + defectQty,
    defectItemIds: [],
    defectItemNames: [],
    defectReason: '',
    rejectReason: '',
    remark: partial.remark || '',
    team: partial.team || '',
    status: partial.status || '待审核',
    ...partial,
    goodQty,
    defectQty,
  }
}

