function loc(partial) {
  return {
    id: partial.id,
    warehouseId: partial.warehouseId,
    warehouseName: partial.warehouseName,
    code: partial.code,
    name: partial.name || partial.code,
    zone: partial.zone || 'A区',
    locationType: partial.locationType || '存储位',
    aisle: partial.aisle || '01',
    rack: partial.rack || '01',
    level: partial.level || '01',
    bin: partial.bin || '01',
    mixSku: partial.mixSku !== false,
    mixBatch: partial.mixBatch !== false,
    maxQty: partial.maxQty ?? null,
    maxWeight: partial.maxWeight ?? null,
    enabled: partial.enabled !== false,
    occupyStatus: partial.occupyStatus || '空闲',
    remark: partial.remark || '',
    creator: partial.creator || 'admin1',
    createdAt: partial.createdAt || '2026-08-01 10:00:00',
  }
}

