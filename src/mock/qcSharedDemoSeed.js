function line(partial = {}) {
  return {
    id: partial.id,
    itemCode: partial.itemCode || '',
    itemName: partial.itemName || '',
    productName: partial.productName || partial.itemName || '',
    specModel: partial.specModel || '',
    material: partial.material || '',
    drawingNo: partial.drawingNo || '',
    unit: partial.unit || '件',
    purchaseQty: partial.purchaseQty,
    receiptQty: partial.receiptQty ?? partial.inspectQty ?? 0,
    shipQty: partial.shipQty,
    inspectQty: partial.inspectQty ?? partial.receiptQty ?? partial.shipQty ?? 0,
    inspectMethod: partial.inspectMethod || '抽检',
    receivingWarehouse: partial.receivingWarehouse || '',
    shipWarehouse: partial.shipWarehouse || '',
    lineQcResult: partial.lineQcResult || '',
    treatmentPlan: partial.treatmentPlan || '',
    acceptInboundQty: partial.acceptInboundQty,
    returnQty: partial.returnQty,
    exchangeQty: partial.exchangeQty,
    fieldValues: Array.isArray(partial.fieldValues) ? partial.fieldValues : [],
    templateId: partial.templateId || '',
    templateCode: partial.templateCode || 'QCT-SYS-001',
    templateName: partial.templateName || '系统通用模板',
    sheetPassRule: partial.sheetPassRule || 'manual',
    sheetConclusionOptionItems: (partial.sheetConclusionOptionItems || CONCLUSION_FULL).map(
      (o) => ({
        ...o,
      }),
    ),
  }
}

