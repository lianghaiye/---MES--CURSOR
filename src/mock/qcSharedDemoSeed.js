function sysFields({
  methodDefault = '抽检',
  remark = true,
  conclusionItems = CONCLUSION_FULL,
} = {}) {
  const items = conclusionItems.map((o) => ({ ...o }))
  const list = [
    {
      code: 'QC_INSPECT_METHOD',
      name: '质检方式',
      type: 'radio',
      required: true,
      options: ['抽检', '全检'],
      defaultValue: methodDefault,
      isPresetInspectMethod: true,
      sortOrder: 1,
    },
    {
      code: 'QC_INSPECT_QTY',
      name: '质检数量',
      type: 'number',
      required: true,
      isPresetInspectQty: true,
      sortOrder: 2,
    },
  ]
  if (remark) {
    list.push({
      code: 'QC_INSPECT_REMARK',
      name: '检验备注',
      type: 'textarea',
      required: false,
      sortOrder: 3,
    })
  }
  list.push({
    code: 'QC_CONCLUSION',
    name: '质检结果',
    type: 'radio',
    required: true,
    isConclusion: true,
    options: items.map((o) => o.value),
    optionItems: items,
    optionResults: Object.fromEntries(items.map((o) => [o.value, o.result])),
    sortOrder: 9999,
  })
  return list
}

