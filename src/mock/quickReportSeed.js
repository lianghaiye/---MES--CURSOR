import dayjs from 'dayjs'
import { normalizeQuickReport, formatReportDate } from '@/mock/quickReports'

function daysAgo(n) {
  return dayjs().subtract(n, 'day').format('YYYY-MM-DD')
}

function atTime(date, time) {
  return `${date} ${time}`
}

function qkNo(date, seq) {
  return `QK-${date.replace(/-/g, '')}-${String(seq).padStart(3, '0')}`
}

/** 工序行快捷构造 */
function proc(id, name, partial = {}) {
  const goodQty = partial.goodQty ?? 0
  const defectQty = partial.defectQty ?? 0
  return {
    id,
    name,
    goodQty,
    defectQty,
    qty: goodQty + defectQty,
    deleted: false,
    operators: partial.operators || ['张三'],
    workHours: partial.workHours ?? null,
    startTime: partial.startTime || '',
    endTime: partial.endTime || '',
    defectBreakdown: partial.defectBreakdown,
    defectItemIds: partial.defectItemIds,
    defectItemNames: partial.defectItemNames,
    subsidyReportQty: partial.subsidyReportQty ?? 0,
    subsidyHours: partial.subsidyHours ?? 0,
    subsidyReason: partial.subsidyReason || '',
    remark: partial.remark || '',
    ...partial,
  }
}

function base(partial) {
  return normalizeQuickReport(partial)
}

