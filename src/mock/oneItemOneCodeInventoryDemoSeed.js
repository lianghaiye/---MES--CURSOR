function upsertById(list, demos, idKey = 'id') {
  const out = Array.isArray(list) ? [...list] : []
  demos.forEach((demo) => {
    const idx = out.findIndex((row) => row?.[idKey] === demo[idKey])
    if (idx === -1) out.unshift(demo)
    else out[idx] = { ...out[idx], ...demo, [idKey]: demo[idKey] }
  })
  return out
}

