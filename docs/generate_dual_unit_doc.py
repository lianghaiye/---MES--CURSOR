def font(run, size=11, bold=False, color=None, name="微软雅黑"):
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = name
    run._element.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), name)
    if color:
        run.font.color.rgb = RGBColor(*color)


def H(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        font(
            r,
            size={1: 18, 2: 14, 3: 12}.get(level, 12),
            bold=True,
            color=(0x1F, 0x4E, 0x79) if level == 1 else (0x2E, 0x75, 0xB6),
        )
    return p


def P(doc, text, *, bold=False, size=11, color=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    font(r, size=size, bold=bold, color=color)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.35
    return p


def B(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    r = p.add_run(text)
    font(r)
    p.paragraph_format.space_after = Pt(3)
    return p


def callout(doc, title, body):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    cell.text = ""
    p1 = cell.paragraphs[0]
    r1 = p1.add_run(title)
    font(r1, size=10, bold=True, color=(0x1F, 0x4E, 0x79))
    for line in body.split("\n"):
        p = cell.add_paragraph()
        r = p.add_run(line)
        font(r, size=10)
        p.paragraph_format.space_after = Pt(2)
    doc.add_paragraph()


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        r = cell.paragraphs[0].add_run(h)
        font(r, size=10, bold=True)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = table.rows[ri + 1].cells[ci]
            cell.text = ""
            r = cell.paragraphs[0].add_run(str(val))
            font(r, size=9)
    doc.add_paragraph()
    return table


